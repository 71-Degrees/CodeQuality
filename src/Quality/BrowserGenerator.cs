using System.Text;
using System.Text.RegularExpressions;
using CodeQuality.Common;

namespace CodeQuality.Quality;

/// <summary>
/// <c>quality browser --generate</c>: writes a browser-test project from the feature list, with no tokens. One test per function: sign in the way the site's seed shortcut allows (for a function that needs a person),
/// start at the home page, click the link text of each "Click ..." step in order, and check the browser ended on one of the function's pages with nothing logged to the console and no server error. It drives the
/// navigation, not the forms: a function whose steps type into a form is exercised up to the form and is not marked walked.
/// </summary>
internal static partial class BrowserGenerator
{
    /// <summary>The files to write, by path relative to the test project. <c>Journeys.cs</c> is rewritten each run; the rest are written once and then belong to the site.</summary>
    internal static IReadOnlyDictionary<string, string> Files(string siteName, BrowserSettings settings, FeatureRegistryFile registry, string toolRelativeToProject, string webProjectRelativeToRoot)
    {
        var project = Identifier(siteName) + ".Browser.Tests";
        return new Dictionary<string, string>
        {
            [project + ".csproj"] = ProjectFile(toolRelativeToProject),
            ["Site.cs"] = SiteClass(project, settings, webProjectRelativeToRoot),
            ["Journey.cs"] = JourneyHelper(project, settings.SignInPath ?? "/"),
            ["Journeys.cs"] = Journeys(project, settings, registry),
        };
    }

    internal static string MethodName(string id) => Regex.Replace(id, "[^A-Za-z0-9_]", "_");

    internal static string Identifier(string text) => NonWord().Replace(text, string.Empty) is { Length: > 0 } id ? id : "Site";

    /// <summary>The click path of a function: the "Click ..." steps up to the first step that is an entry, or the first page without a route parameter when it has no click steps. Empty: nothing a browser can walk to.</summary>
    internal static IReadOnlyList<string> ClickPath(FeatureFunction function) =>
        [.. function.Steps.TakeWhile(s => s.StartsWith("Click ", StringComparison.Ordinal)).Select(s => s["Click ".Length..].Trim())];

    internal static string? StartPage(FeatureFunction function) => function.Routes.FirstOrDefault(r => !r.Contains('{', StringComparison.Ordinal));

    private static string Journeys(string project, BrowserSettings settings, FeatureRegistryFile registry)
    {
        var tests = new StringBuilder();
        var skipped = new List<string>();
        foreach (var function in registry.Functions)
        {
            var path = ClickPath(function);
            if (StartPage(function) is null)
            {
                skipped.Add(function.Id);
                continue;
            }

            tests.Append(Test(function, path, settings.SignInPath is not null && !function.Who.Equals("Anyone", StringComparison.OrdinalIgnoreCase)));
        }

        var header = skipped.Count == 0 ? string.Empty : $"// No test (only pages with a route parameter, so a person has to pick a record first): {string.Join(", ", skipped)}\n";
        return $$"""
            {{Header}}

            using CodeQuality.Browser;

            namespace {{project}};

            // GENERATED by `quality browser --generate` from quality/features.json - rewritten on every run, so change the feature list (or add tests beside this file), not this file.
            {{header}}public sealed class Journeys(Site site) : IClassFixture<Site>
            {
            {{tests.ToString().TrimEnd()}}
            }

            """;
    }

    private static string Test(FeatureFunction function, IReadOnlyList<string> path, bool signedIn)
    {
        var walk = path.Count > 0
            ? $"await Journey.FollowAsync(site, page, {(StartPage(function) is { } fallback ? Literal(fallback) : "null")}, {string.Join(", ", path.Select(Literal))});"
            : $"await Journey.StartAsync(site, page, {Literal(StartPage(function)!)});";
        var pages = string.Join(", ", function.Routes.Select(r => Literal(Base(r))));
        var signIn = signedIn ? "            await Journey.SignInAsync(site, journey.Page);\n" : string.Empty;
        return $$"""
                [BrowserFact]
                public async Task {{MethodName(function.Id)}}()
                {
                    await using var journey = await site.NewPageAsync(1280, 800);
            {{signIn}}        await journey.RunAsync({{Literal(function.Id)}}, async page =>
                    {
                        {{walk}}
                        Journey.AssertOnOneOf(page, {{pages}});
                    });
                }


            """;
    }

    /// <summary>The page's address up to a route parameter, so <c>/chronicle/{Slug}</c> is satisfied by any chronicle.</summary>
    internal static string Base(string route) => route.Contains('{', StringComparison.Ordinal) ? route[..route.IndexOf('{', StringComparison.Ordinal)] : route;

    private static string Literal(string text) => "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    private const string Header = "/*\n * ---------------------------------------------------------------------------\n * Copyright © 2026 71 Degrees. All rights reserved.\n * ---------------------------------------------------------------------------\n */";

    private static string ProjectFile(string toolRelativeToProject) => $"""
        <Project Sdk="Microsoft.NET.Sdk">

          <!-- Real-browser tests: the site runs as its own process and Playwright's Chromium drives it. On demand (dotnet test on this project); skipped, with the reason, where Chromium is not installed.
               Generated by the quality tool (browser, generate); the shared machinery lives in the CodeQuality submodule (Quality.Browser). -->
          <PropertyGroup>
            <TargetFramework>net10.0</TargetFramework>
            <ImplicitUsings>enable</ImplicitUsings>
            <Nullable>enable</Nullable>
            <IsPackable>false</IsPackable>
            <IsTestProject>true</IsTestProject>
          </PropertyGroup>

          <ItemGroup>
            <PackageReference Include="Microsoft.NET.Test.Sdk" Version="17.8.0" />
            <PackageReference Include="xunit" Version="2.5.3" />
            <PackageReference Include="xunit.runner.visualstudio" Version="2.5.3" />
          </ItemGroup>

          <ItemGroup>
            <Using Include="Xunit" />
          </ItemGroup>

          <ItemGroup>
            <ProjectReference Include="{toolRelativeToProject}\src\Quality.Browser\Quality.Browser.csproj" />
          </ItemGroup>

        </Project>

        """;

    private static string SiteClass(string project, BrowserSettings settings, string webProject)
    {
        var environment = string.Concat(new Dictionary<string, string> { ["ASPNETCORE_ENVIRONMENT"] = "Development" }.Concat(settings.Environment).Select(p => $"            [{Literal(p.Key)}] = {Literal(p.Value)},\n"));
        return $$"""
            {{Header}}

            using CodeQuality.Browser;

            namespace {{project}};

            /// <summary>How the site starts for a browser test: the real site in Development, on a free port, and nothing that reaches an outside service. Written once by `quality browser --generate`; it is the site's now.</summary>
            public sealed class Site : BrowserSiteFixture
            {
                private static readonly string Root = FindRepositoryRoot();

                protected override string RunLogPath => Path.Combine(Root, "reports", "browser-runs.jsonl");

                protected override bool BlocksRequest(Uri address) => address.Scheme is "http" or "https" && address.Host is not ("127.0.0.1" or "localhost");

                protected override SiteHostOptions Options => new()
                {
                    ProjectPath = Path.Combine(Root, {{Literal(webProject.Replace('\\', '/'))}}),
                    ReadyPath = {{Literal(settings.ReadyPath)}},
                    Environment = new Dictionary<string, string>
                    {
            {{environment.TrimEnd()}}
                    },
                };

                private static string FindRepositoryRoot()
                {
                    var folder = new DirectoryInfo(AppContext.BaseDirectory);
                    while (folder is not null && !Directory.Exists(Path.Combine(folder.FullName, ".git")) && !File.Exists(Path.Combine(folder.FullName, ".git")))
                    {
                        folder = folder.Parent;
                    }

                    return folder?.FullName ?? throw new InvalidOperationException("The repository root (.git) was not found above " + AppContext.BaseDirectory);
                }
            }

            """;
    }

    private static string JourneyHelper(string project, string signInPath) => $$"""
        {{Header}}

        using CodeQuality.Browser;
        using Microsoft.Playwright;

        namespace {{project}};

        /// <summary>The few things every generated journey does. Written once by `quality browser --generate`; it is the site's now.</summary>
        internal static class Journey
        {
            public static Task StartAsync(Site site, IPage page, string path) => page.GotoLiveAsync(site.BaseUrl + path);

            /// <summary>Signs the test visitor in through the site's own seed shortcut (<c>browser.signInPath</c> in quality.json), which redirects when it is done.</summary>
            public static Task SignInAsync(Site site, IPage page) => page.GotoLiveAsync(site.BaseUrl + SignInPath);

            /// <summary>
            /// Starts at the home page and clicks the first link (or button) showing each text, waiting for each page to be live. A text that is not there within 5 seconds (it needs data the site does not have yet, or sits
            /// behind a menu) falls back to opening the function's page by its address, so the page is still visited and checked.
            /// </summary>
            public static async Task FollowAsync(Site site, IPage page, string? fallback, params string[] texts)
            {
                await StartAsync(site, page, "/");
                foreach (var text in texts)
                {
                    var target = page.GetByRole(AriaRole.Link, new() { Name = text }).Or(page.GetByRole(AriaRole.Button, new() { Name = text })).First;
                    try
                    {
                        await target.ClickAsync(new() { Timeout = 5_000 });
                    }
                    catch (TimeoutException) when (fallback is not null)
                    {
                        await StartAsync(site, page, fallback);
                        return;
                    }

                    await page.WaitForLoadStateAsync(LoadState.NetworkIdle);
                }
            }

            public static void AssertOnOneOf(IPage page, params string[] bases)
            {
                var path = new Uri(page.Url).AbsolutePath;
                if (!bases.Any(b => b == "/" ? path == "/" : path.StartsWith(b.TrimEnd('/'), StringComparison.OrdinalIgnoreCase)))
                {
                    throw new BrowserProblemException($"Ended on {path}, expected one of: {string.Join(", ", bases)}");
                }
            }

            private const string SignInPath = {{Literal(signInPath)}};
        }

        """;

    [GeneratedRegex(@"[^A-Za-z0-9]")]
    private static partial Regex NonWord();
}
